// 状态变量
const currentPattern = ref(null);
const currentIndex = ref(0);
const keyPressCount = ref(0);
const isDrawingComplete = ref(false);

// 获取随机图案
function getRandomPattern() {
  const keys = Object.keys(patterns);
  const randomKey = keys[Math.floor(Math.random() * keys.length)];
  return {
    name: randomKey,
    points: patterns[randomKey]
  };
}

// 添加波浪线
function addWave() {
  const box = contentBox.value;
  if (!box || isDrawingComplete.value) return;

  // 增加按键计数
  keyPressCount.value++;

  // 每按两次键才绘制一个波浪线
  if (keyPressCount.value % 2 !== 0) {
    return;
  }

  // 确保有当前图案
  if (!currentPattern.value) {
    return;
  }

  const boxRect = box.getBoundingClientRect();
  const centerX = boxRect.width / 2;
  const centerY = boxRect.height / 2;

  const point = currentPattern.value.points[currentIndex.value];
  if (!point) return;

  const waveX = centerX + point.x;
  const waveY = centerY + point.y;

  waves.push({
    style: {
      position: 'absolute',
      top: `${waveY}px`,
      left: `${waveX}px`,
    },
    svg: waveSvg,
  });

  // 更新索引
  currentIndex.value++;

  // 检查是否已完成图案绘制
  if (currentIndex.value >= currentPattern.value.points.length) {
    isDrawingComplete.value = true;
    // 移除键盘事件监听
    window.removeEventListener('keydown', handleKeyDown);
    console.log(`图案 ${currentPattern.value.name} 绘制完成！`);
  }
}

// 处理键盘事件
function handleKeyDown(e) {
  addWave();
}

// 初始化图案
function initPattern() {
  // 随机选择一个图案
  currentPattern.value = getRandomPattern();
  currentIndex.value = 0;
  keyPressCount.value = 0;
  isDrawingComplete.value = false;
  waves.length = 0; // 清空现有波浪线
  
  console.log(`已选择图案: ${currentPattern.value.name}，共 ${currentPattern.value.points.length} 个点`);
}

// 生命周期钩子
onMounted(() => {
  // 初始化图案
  initPattern();
  
  // 添加键盘事件监听
  window.addEventListener('keydown', handleKeyDown);
});

onBeforeUnmount(() => {
  // 移除键盘事件监听
  window.removeEventListener('keydown', handleKeyDown);
});
